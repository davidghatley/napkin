// Regenerates src/css-props.js from the CSSProperties type that React's types ship (csstype).
//   node tools/gen-css-props.mjs
// For each property it asks the TypeScript checker whether a number and a plain string may be assigned to it, so napkin
// can refuse an edit that would make a component fail `tsc --strict` (an unknown property, or `background: 8`).
import ts from 'typescript';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const probe = join(root, 'tools', '.probe.ts');
const host = ts.createCompilerHost({});
const read = host.readFile.bind(host);
host.readFile = (f) => (f === probe ? `import type { CSSProperties } from 'react'; export type P = CSSProperties;` : read(f));
host.fileExists = ((orig) => (f) => f === probe || orig(f))(host.fileExists.bind(host));
const program = ts.createProgram([probe], {
  strict: true, noEmit: true, skipLibCheck: true, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext, types: [],
  paths: { react: [join(root, 'node_modules/@types/react')] },
}, host);
const checker = program.getTypeChecker();
const sf = program.getSourceFile(probe);
const P = checker.getTypeAtLocation(sf.statements.at(-1).name);
const numberT = checker.getNumberType(), stringT = checker.getStringType();
const all = [], numeric = [];
for (const sym of checker.getPropertiesOfType(P)) {
  const name = sym.getName();
  if (!/^[a-z][a-zA-Z]*$/.test(name)) continue; // vendor-prefixed (WebkitX) and custom names are not offered
  const t = checker.getNonNullableType(checker.getTypeOfSymbol(sym));
  const accepts = (x) => checker.isTypeAssignableTo(x, t);
  all.push(name);
  if (accepts(numberT)) numeric.push(name);
}
all.sort(); numeric.sort();
const wrap = (a) => { const lines = []; let line = ''; for (const n of a) { if ((line + n).length > 100) { lines.push(line.trimEnd()); line = ''; } line += `${n} `; } lines.push(line.trimEnd()); return lines.map((l) => `  '${l} '`).join(' +\n'); };
writeFileSync(join(root, 'src', 'css-props.js'), `// GENERATED by tools/gen-css-props.mjs from React's CSSProperties (csstype). Do not edit by hand.
// A style edit must use a property that exists and, for a number, one that takes numbers: otherwise the component
// would not pass \`tsc --strict\` (FMT-03). Plain, so the canvas page can load it with the model.
const words = (s) => new Set(s.trim().split(' '));
export const CSS_PROPS = words(
${wrap(all)}
);
export const CSS_NUMBER_PROPS = words(
${wrap(numeric)}
);
`);
console.log(`${all.length} properties, ${numeric.length} take numbers`);
