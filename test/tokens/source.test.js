test('TOK-01/05: HTTP and MCP parity, authenticated permission guard, disk reload, activity', async () => {
  const { dir, compDir } = tempRepo(['Card']);
  cpSync(join(ROOT, 'fixtures/tokens'), join(dir, 'tokens'), { recursive: true });
  writeFileSync(join(dir, 'napkin.json'), JSON.stringify({ tokens: { source: 'tokens/tokens.json', css: 'tokens/tokens.css' }, agents: { you: 'write', observer: 'read', reviewer: 'propose' } }));
  const server = await startServer(compDir), mcp = await startMcp(server.url);
  const get = async () => (await fetch(new URL('api/tokens', server.url))).json();
  const post = (body, token) => fetch(new URL('api/tokens', server.url), { method: 'POST', headers: { 'content-type': 'application/json', ...(token && { authorization: `Bearer ${token}` }) }, body: JSON.stringify(body) });
  try {
    const a = await get(); assert.equal(a.tokens.length, 20);
    assert.deepEqual((await mcp.call('list_tokens')).data.tokens, a.tokens);
    const body = { name: 'accent', mode: 'dark', value: '#aabbff', baseRevision: a.revision, by: 'spoof' };
    assert.equal((await post(body)).status, 401);
    for (const as of ['observer', 'reviewer', 'you']) {
      const sess = await (await fetch(new URL('api/session', server.url), { method: 'POST', body: JSON.stringify({ as }) })).json();
      assert.equal((await post(body, sess.token)).status, as === 'you' ? 200 : 403);
    }
    const activity = await (await fetch(new URL('api/activity', server.url))).json();
    assert.equal(activity.activity[0].by, 'you'); assert.equal(activity.activity[0].kind, 'tokens');
    const file = join(dir, 'tokens/tokens.json');
    writeFileSync(file, readFileSync(file, 'utf8').replace('#aabbff', '#bbccff'));
    await waitFor(async () => (await get()).tokens.find(t => t.name === 'accent').values.dark === '#bbccff');
  } finally { mcp.stop(); await server.stop(); }
});

