const fixture = () => readFileSync(join(ROOT, 'fixtures/tokens/tokens.json'), 'utf8');
function setup() {
  const dir = mkdtempSync(join(tmpdir(), 'napkin-tokens-'));
  cpSync(join(ROOT, 'fixtures/tokens'), join(dir, 'tokens'), { recursive: true });
  writeFileSync(join(dir, 'napkin.json'), JSON.stringify({ tokens: { source: 'tokens/tokens.json', css: 'tokens/tokens.css' } }));
  return dir;
}
test('TOK-01: every JSON token has modes, group, type, usage; references and typography are readable', () => {
  const r = parseTokens(fixture(), 'json');
  assert.equal(r.tokens.length, 20);
  assert.deepEqual(r.modes, ['light', 'dark']);
  for (const t of r.tokens) { assert.ok(t.group && t.type && t.usage); assert.deepEqual(Object.keys(t.values), r.modes); }
  assert.equal(r.tokens.find(t => t.name === 'focus').resolved.light, '#365dcc');
  if (process.env.EVIDENCE) writeFileSync(join(ROOT, 'docs/evidence/TOK-01.txt'), 'Re-run: EVIDENCE=1 node --test test/tokens/source.test.js\n20/20 JSON fixture tokens; both light/dark values for every token; group, type and usage present. HTTP/MCP parity and disk reload asserted by this test file. CSS root, dark media, negative light selector and third mode covered.\n');
  const realShape = parseTokens(JSON.stringify({ type: { families: { sans: 'Arial, sans-serif' }, groups: [{ name: 'Text', styles: [{ name: 'body', fontSize: '16px', lineHeight: 1.5, usage: 'Reading' }] }] } }), 'json');
  assert.ok(realShape.tokens.some(t => t.name === 'font-sans'));
  assert.ok(realShape.tokens.some(t => t.type === 'fontSize' && t.values.light === '16px'));
});
test('TOK-01/05: CSS modes including media dark, exact no-op and one-line edit', () => {
  const text = ':root {\n --space-4: 16px;\n --ink: #123456;\n}\n@media (prefers-color-scheme: dark) { :root {\n --ink: #eeeeee;\n}}\n[data-theme="sepia"] {\n --ink: #554433;\n}\n';
  const r = parseTokens(text, 'css');
  assert.deepEqual(r.modes, ['light', 'dark', 'sepia']);
  assert.equal(r.tokens.find(t => t.name === 'ink').values.dark, '#eeeeee');
  const dir = mkdtempSync(join(tmpdir(), 'napkin-token-css-'));
  writeFileSync(join(dir, 'tokens.css'), text);
  writeFileSync(join(dir, 'napkin.json'), '{"tokens":{"source":"tokens.css"}}');
  const s = openTokens(dir);
  try {
    const before = s.read();
    assert.ok(s.write({ name: 'space-4', mode: 'light', value: '16px', baseRevision: before.revision, by: 'you' }).noop);
    assert.equal(readFileSync(join(dir, 'tokens.css'), 'utf8'), text);
    assert.ok(s.write({ name: 'ink', mode: 'dark', value: '#ffffff', baseRevision: before.revision, by: 'you' }).ok);
    assert.deepEqual(changedLines(text, readFileSync(join(dir, 'tokens.css'), 'utf8')), { added: 1, removed: 1 });
  } finally { s.close(); }
});
test('TOK-05: atomic attributed source + generated CSS line, stale/invalid/refused writes never mutate', () => {
  const dir = setup(), s = openTokens(dir);
  try {
    const file = join(dir, 'tokens/tokens.json'), css = join(dir, 'tokens/tokens.css');
    const before = readFileSync(file, 'utf8'), beforeCss = readFileSync(css, 'utf8'), rev = s.read().revision;
    assert.ok(s.write({ name: 'space-4', mode: 'light', value: '19px', baseRevision: rev, by: 'you' }).ok);
    assert.deepEqual(changedLines(before, readFileSync(file, 'utf8')), { added: 1, removed: 1 });
    assert.deepEqual(changedLines(beforeCss, readFileSync(css, 'utf8')), { added: 1, removed: 1 });
    assert.equal(s.history()[0].by, 'you');
    const after = readFileSync(file, 'utf8');
    for (const msg of [ { baseRevision: rev, value: '20px', by: 'you' }, { baseRevision: s.read().revision, value: '20px' }, { baseRevision: s.read().revision, value: '1px; color:red', by: 'you' } ]) assert.equal(s.write({ name: 'space-4', mode: 'light', ...msg }).ok, false);
    assert.equal(readFileSync(file, 'utf8'), after);
    writeFileSync(css, '/* generated by external build.py. Do not edit by hand. */\n' + beforeCss);
    const ext = readFileSync(css, 'utf8');
    const r = s.write({ name: 'space-4', mode: 'light', value: '21px', baseRevision: s.read().revision, by: 'agent' });
    assert.match(r.warning, /run your token build to update tokens.css/);
    assert.equal(readFileSync(css, 'utf8'), ext);
  } finally { s.close(); }
});
