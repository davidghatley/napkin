test('TOK-05: runtime fs spy sees source/CSS renames only through commit.writeTokens', async () => {
  const { mock } = await import('node:test');
  const fs = (await import('node:fs')).default;
  const { syncBuiltinESMExports } = await import('node:module');
  const dir = setup(), calls = [], original = fs.renameSync;
  const spy = mock.method(fs, 'renameSync', function(...args) { calls.push(new Error().stack); return original.apply(this, args); });
  syncBuiltinESMExports();
  const s = openTokens(dir);
  try {
    assert.ok(s.write({ name: 'accent', mode: 'light', value: '#111111', baseRevision: s.read().revision, by: 'you' }).ok);
    assert.equal(calls.length, 2);
    for (const stack of calls) assert.match(stack, /writeTokens.*src\/commit\.js/);
  } finally { s.close(); spy.mock.restore(); syncBuiltinESMExports(); }
});

