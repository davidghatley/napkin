// Writes the stories (storybook/stories/**) and INVENTORY.md from inventory.mjs + fixtures/manifest.json.
// Run by capture.mjs; also runnable alone: node storybook/generate.mjs
import { writeFileSync, readFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ITEMS, LEVELS } from './inventory.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const DIRS = { 1: '1-interface', 2: '2-panels', 3: '3-components' };

export function generate() {
  const manifest = JSON.parse(readFileSync(join(HERE, 'fixtures/manifest.json'), 'utf8'));
  for (const d of Object.values(DIRS)) { rmSync(join(HERE, 'stories', d), { recursive: true, force: true }); mkdirSync(join(HERE, 'stories', d), { recursive: true }); }
  const counts = { 1: 0, 2: 0, 3: 0 }, stateCounts = { 1: 0, 2: 0, 3: 0 };
  for (const it of ITEMS) {
    const states = manifest.items[it.id]?.states || [];
    if (!states.length) continue;
    counts[it.level]++; stateCounts[it.level] += states.length;
    const title = `${LEVELS[it.level]}/${it.id} ${it.name}`;
    const src = `// GENERATED by storybook/generate.mjs from inventory.mjs and the captured fixtures. Do not edit; re-run capture.
import { fixture } from '../../lib/mount.js';

export default { title: ${JSON.stringify(title)}, parameters: { layout: 'fullscreen' } };
${states.map((s, i) => `
export const S${String(i + 1).padStart(2, '0')} = { name: ${JSON.stringify('Current · ' + s.name)}, render: (args, ctx) => fixture(${JSON.stringify(s.key)}, ctx) };`).join('')}
`;
    writeFileSync(join(HERE, 'stories', DIRS[it.level], `${it.id}.stories.js`), src);
  }
  // INVENTORY.md
  const lines = [];
  lines.push('# napkin interface inventory', '', 'Every part of napkin\'s interface, largest to smallest, found from the running app (`src/cli.js open` on the `ss-ds` corpus folder) and then captured as fixtures by `storybook/capture.mjs`. This file is generated by `storybook/generate.mjs` from `storybook/inventory.mjs`; edit the inventory, not this file.', '', 'Run it: `npm ci` then `npm run storybook` (http://127.0.0.1:6006, localhost only). Re-capture the fixtures from the live app with `npm run storybook:capture`; check every story with `node storybook/check.mjs`. In the Feedback panel under each story pick keep / change / drop and write a note; it is saved to `storybook/feedback/feedback.json`. The sidebar shows a tick on reviewed stories and a count on items.', '', 'Ids are stable: `I` = Level 1 interface, `P` = Level 2 panel, `C` = Level 3 component. A story is named `Current · <state>`; variations are named `Variation NN · <idea>` (see VARIATIONS.md).', '');
  lines.push('| Level | Items | States (stories) |', '|---|---|---|');
  for (const l of [1, 2, 3]) lines.push(`| ${l} ${LEVELS[l].slice(2)} | ${counts[l]} | ${stateCounts[l]} |`);
  lines.push(`| Total | ${counts[1] + counts[2] + counts[3]} | ${stateCounts[1] + stateCounts[2] + stateCounts[3]} |`, '');
  for (const l of [1, 2, 3]) {
    lines.push(`## Level ${l}: ${LEVELS[l].slice(2)} (${counts[l]})`, '', '| Id | Name | Source | What it is for | States |', '|---|---|---|---|---|');
    for (const it of ITEMS.filter((x) => x.level === l)) {
      const got = manifest.items[it.id]?.states || [];
      if (!got.length) continue;
      lines.push(`| ${it.id} | ${it.name} | ${it.files.map((f) => '`' + f + '`').join(', ')} | ${it.purpose} | ${got.length}: ${got.map((s) => s.name).join('; ')} |`);
    }
    lines.push('');
  }
  if (manifest.skipped.length || ITEMS.some((it) => !(manifest.items[it.id]?.states || []).length)) {
    lines.push('## Not captured', '');
    for (const it of ITEMS) if (!(manifest.items[it.id]?.states || []).length) lines.push(`- ${it.id} ${it.name}: no state could be captured`);
    for (const s of manifest.skipped) lines.push(`- ${s.id} state "${s.state}": ${s.why}`);
    lines.push('');
  }
  writeFileSync(join(HERE, 'INVENTORY.md'), lines.join('\n'));
  return { counts, stateCounts };
}
if (import.meta.url === pathToFileURL(process.argv[1]).href) console.log(generate());
